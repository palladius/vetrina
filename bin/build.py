#!/usr/bin/env python3
"""
Sync script: Compiles data/games.yaml into data/games.json and assets/js/games-data.js
Ensures the site works both via HTTP server (fetch) and directly via file:// URLs.
"""

import os
import json
import yaml

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
YAML_FILE = os.path.join(PROJECT_ROOT, "data", "games.yaml")
JSON_FILE = os.path.join(PROJECT_ROOT, "data", "games.json")
JS_DATA_FILE = os.path.join(PROJECT_ROOT, "assets", "js", "games-data.js")

def main():
    print(f"📖 Reading {YAML_FILE}...")
    with open(YAML_FILE, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)

    print(f"✅ Loaded {len(data)} items from YAML.")

    # Validate screenshots and ensure default score
    for item in data:
        if "score" not in item or item["score"] is None:
            item["score"] = 50
        shot = item.get("screenshot")
        if shot:
            full_path = os.path.join(PROJECT_ROOT, shot)
            exists = os.path.isfile(full_path)
            status = "FOUND" if exists else "MISSING"
            print(f"   [{status}] {item['id']}: {shot} (Score: {item['score']})")

    # Write data/games.json
    os.makedirs(os.path.dirname(JSON_FILE), exist_ok=True)
    with open(JSON_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"💾 Generated {JSON_FILE}")

    # Write assets/js/games-data.js as safe global fallback
    os.makedirs(os.path.dirname(JS_DATA_FILE), exist_ok=True)
    js_content = f"// Auto-generated by bin/build.py from data/games.yaml\nwindow.PALLADIUS_GAMES = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    with open(JS_DATA_FILE, "w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"💾 Generated {JS_DATA_FILE}")

if __name__ == "__main__":
    main()
